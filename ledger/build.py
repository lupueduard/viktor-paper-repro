"""Render LEDGER.md from ledger/papers/*.toml.

    python ledger/build.py           # rewrite LEDGER.md
    python ledger/build.py --check   # exit 1 if LEDGER.md is out of date or an entry is invalid

Standard library only (Python 3.11+).
"""
from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAPERS_DIR = ROOT / "ledger" / "papers"
LEDGER = ROOT / "LEDGER.md"
REPO_URL = "https://github.com/lupueduard/viktor-paper-repro"

VERDICTS = {
    "held": "✅ Held",
    "partly": "🟡 Partly",
    "did-not-hold": "❌ Didn't hold",
}
PAPER_KEYS = {"title", "arxiv", "folder", "pr", "tested", "setup"}
CLAIM_KEYS = {"claim", "verdict", "evidence"}
ARXIV_RE = re.compile(r"^\d{4}\.\d{4,5}$")


class LedgerError(ValueError):
    pass


def load_entry(path: Path) -> dict:
    """Parse and validate one paper file."""
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as e:
        raise LedgerError(f"{path.name}: not valid TOML ({e})") from e
    paper, claims = data.get("paper"), data.get("claims")
    if not isinstance(paper, dict):
        raise LedgerError(f"{path.name}: missing [paper] table")
    _check_keys(path.name, "[paper]", paper, PAPER_KEYS)
    if not ARXIV_RE.match(str(paper["arxiv"])):
        raise LedgerError(f"{path.name}: arxiv {paper['arxiv']!r} should look like 2610.09239 (no version)")
    if not isinstance(paper["pr"], int) or paper["pr"] < 1:
        raise LedgerError(f"{path.name}: pr should be the pull request number, e.g. pr = 1")
    if not isinstance(paper["tested"], dt.date):
        raise LedgerError(f"{path.name}: tested should be an unquoted date, e.g. tested = 2026-11-25")
    if not claims:
        raise LedgerError(f"{path.name}: add at least one [[claims]] block")
    for i, claim in enumerate(claims, 1):
        _check_keys(path.name, f"claim {i}", claim, CLAIM_KEYS)
        if claim["verdict"] not in VERDICTS:
            raise LedgerError(
                f"{path.name}: claim {i} verdict {claim['verdict']!r}; use one of {', '.join(VERDICTS)}"
            )
    return {"paper": paper, "claims": claims}


def _check_keys(name: str, where: str, table: dict, required: set[str]) -> None:
    missing = sorted(required - table.keys())
    extra = sorted(table.keys() - required)
    if missing:
        raise LedgerError(f"{name}: {where} is missing {', '.join(missing)}")
    if extra:
        raise LedgerError(f"{name}: {where} has unknown key(s) {', '.join(extra)}")
    for key in required:
        if isinstance(table[key], str) and not table[key].strip():
            raise LedgerError(f"{name}: {where} has an empty {key}")


def load_all(papers_dir: Path | None = None) -> list[dict]:
    papers_dir = papers_dir or PAPERS_DIR
    entries = [load_entry(p) for p in sorted(papers_dir.glob("*.toml")) if not p.name.startswith("_")]
    # Newest first; ties broken by title so the output is stable.
    entries.sort(key=lambda e: (-e["paper"]["tested"].toordinal(), e["paper"]["title"]))
    return entries


def _plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def render(entries: list[dict]) -> str:
    counts = {v: 0 for v in VERDICTS}
    for e in entries:
        for c in e["claims"]:
            counts[c["verdict"]] += 1
    n_claims = sum(counts.values())
    summary = ", ".join(f"{counts[v]} {VERDICTS[v].split(' ', 1)[1].lower()}" for v in VERDICTS)

    lines = [
        "# Claims ledger",
        "",
        "<!-- Generated by ledger/build.py from ledger/papers/*.toml. Edit those files, not this one. -->",
        "",
        "Every paper claim we have tested, one row per claim, newest paper first.",
        f"{_plural(len(entries), 'paper')}, {_plural(n_claims, 'claim')}: {summary}.",
        "",
        "✅ Held: our numbers match the claim. 🟡 Partly: right direction, but the size or significance",
        "differs, or only part of the claim held. ❌ Didn't hold: our numbers contradict the claim or show no effect.",
        "",
        "| Paper | Claim | Our setup | Verdict | Evidence | PR |",
        "|---|---|---|---|---|---|",
    ]
    for e in entries:
        p = e["paper"]
        paper_cell = (
            f"[{_cell(p['title'])}](https://arxiv.org/abs/{p['arxiv']})<br>"
            f"[`{p['folder']}/`]({p['folder']}/) · {p['tested'].isoformat()}"
        )
        pr_cell = f"[#{p['pr']}]({REPO_URL}/pull/{p['pr']})"
        for i, c in enumerate(e["claims"]):
            first = i == 0
            lines.append(
                "| "
                + " | ".join(
                    [
                        paper_cell if first else "〃",
                        _cell(c["claim"]),
                        _cell(p["setup"]) if first else "〃",
                        VERDICTS[c["verdict"]],
                        _cell(c["evidence"]),
                        pr_cell if first else "〃",
                    ]
                )
                + " |"
            )
    lines += [
        "",
        "## Adding a paper",
        "",
        "1. Copy `ledger/papers/_TEMPLATE.toml` to `ledger/papers/<paper-slug>.toml` and fill it in,",
        "   one `[[claims]]` block per claim tested.",
        "2. Run `python ledger/build.py` to regenerate this file, and commit both.",
        "",
        "`python ledger/build.py --check` fails if this file is stale or an entry is invalid.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify LEDGER.md is up to date; write nothing")
    args = ap.parse_args(argv)
    try:
        text = render(load_all())
    except LedgerError as e:
        print(f"ledger error: {e}", file=sys.stderr)
        return 1
    if args.check:
        current = LEDGER.read_text(encoding="utf-8") if LEDGER.exists() else ""
        if current != text:
            print("LEDGER.md is out of date: run python ledger/build.py and commit it.", file=sys.stderr)
            return 1
        print("LEDGER.md is up to date.")
        return 0
    LEDGER.write_text(text, encoding="utf-8")
    print(f"wrote {LEDGER.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
